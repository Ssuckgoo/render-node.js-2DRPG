// 보스는 기존 스프라이트에 왕관/색 변형
function withCrown(rows) {
  const r = rows.slice();
  r[0] = '.....y.y.y......';
  r[1] = '.....yyyyy......';
  return r;
}
SPRITES.goblin_king = withCrown(SPRITES.goblin);
SPRITES.lich = withCrown(SPRITES.skeleton);
const SPRITE_PAL = {
  lich: { w: '#c9b8ff', r: '#00ffd0' },
  goblin_king: { N: '#7d1f1f', n: '#c8433a' },
};

const spriteCache = {};
function buildSprite(name, flash) {
  const key = name + (flash ? ':f' : '');
  if (spriteCache[key]) return spriteCache[key];
  const rows = SPRITES[name] || SPRITES.slime;
  const pal = Object.assign({}, PAL, SPRITE_PAL[name] || {});
  const c = document.createElement('canvas');
  c.width = 16; c.height = 16;
  const ctx = c.getContext('2d');
  rows.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const ch = row[x];
      if (!ch || ch === '.') continue;
      ctx.fillStyle = flash ? '#ffffff' : (pal[ch] || '#ff00ff');
      ctx.fillRect(x, y, 1, 1);
    }
  });
  spriteCache[key] = c;
  return c;
}
